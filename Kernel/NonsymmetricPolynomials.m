familyPolynomial["FundamentalSlide", alpha_, n_] := FundamentalSlidePolynomial[alpha, xx];
familyPolynomial["Lock", alpha_, n_] := LockPolynomial[alpha, xx];
familyPolynomial["Lascoux", alpha_, n_] := LascouxPolynomial[alpha, xx];
