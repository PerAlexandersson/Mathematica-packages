toFamilyBasis[family_, poly_, x_, nIn_] := Module[{p = Expand[poly], vars, n, s, total = 0},
	vars = Union@Cases[p, x[i_Integer] :> i, {0, Infinity}];
	n = Max[Append[vars, 1], nIn];
	(* Convert each homogeneous component separately. *)
	Do[With[{pd = Coefficient[Expand[p /. x[i_] :> s x[i]], s, d]},
		If[pd =!= 0,
			Module[{indices, inv, vec},
				{indices, inv} = transitionInverse[family, d, n];
				vec = coefficientVector[pd, x, indices, n];
				total += (vec . inv) . (familySymbol[family, #, x] & /@ indices)]]],
		{d, 0, Exponent[p /. x[i_] :> s x[i], s]}];
	total
];

