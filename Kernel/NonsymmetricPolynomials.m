(* Coefficients of the monomials x^beta, beta in indices, of the polynomial p in x[1..n]. *)
coefficientVector[p_, x_, indices_, n_] := With[
	{rules = Association[CoefficientRules[p, x /@ Range[n]]]},
	Lookup[rules, Key /@ indices, 0]];

expansionVector[family_, alpha_, indices_, n_] :=
	coefficientVector[familyPolynomial[family, alpha, n], xx, indices, n];

