(* Families generated by operators *)

weakCompositionQ[alpha_] := VectorQ[alpha, IntegerQ[#] && # >= 0 &];

(* A word {i1, ..., ik} with s_i1 ... s_ik (sort(alpha)) = alpha, where s_i swaps
   positions i and i+1; the last letter acts first. Obtained by bubble-sorting alpha
   into weakly decreasing order. *)
sortingWord[alpha_List] := Module[{a = alpha, word = {}, swapped = True},
	While[swapped,
		swapped = False;
		Do[If[a[[i]] < a[[i + 1]],
			a[[{i, i + 1}]] = a[[{i + 1, i}]]; AppendTo[word, i]; swapped = True],
			{i, Length[a] - 1}]];
	word
];

monomial[alpha_List, x_] := Times @@ MapIndexed[x[First[#2]]^#1 &, alpha];

KeyPolynomial::usage = "KeyPolynomial[alpha, x] returns the key polynomial (Demazure character) kappa_alpha in x[1], x[2], ... for a weak composition alpha, computed as pi_w x^sort(alpha) with Demazure operators. Standard indexing: KeyPolynomial[{0, 1}, x] is x[1] + x[2].";
KeyPolynomial[alpha_?weakCompositionQ, x_] := cached[{KeyPolynomial, alpha},
	DemazureOperator[monomial[Sort[alpha, Greater], xx], xx, sortingWord[alpha]]] /. xx -> x;

AtomPolynomial::usage = "AtomPolynomial[alpha, x] returns the Demazure atom A_alpha in x[1], x[2], ... for a weak composition alpha, computed as theta_w x^sort(alpha). Standard indexing: AtomPolynomial[{0, 1}, x] is x[2].";
AtomPolynomial[alpha_?weakCompositionQ, x_] := cached[{AtomPolynomial, alpha},
	DemazureAtomOperator[monomial[Sort[alpha, Greater], xx], xx, sortingWord[alpha]]] /. xx -> x;

TKeyPolynomial::usage = "TKeyPolynomial[alpha, x, t] returns the t-deformed key polynomial obtained by applying TDemazureOperator along the sorting word of alpha to x^sort(alpha); t = 0 gives KeyPolynomial.";
TKeyPolynomial[alpha_?weakCompositionQ, x_, t_] := cached[{TKeyPolynomial, alpha},
	TDemazureOperator[monomial[Sort[alpha, Greater], xx], xx, tt, sortingWord[alpha]]] /. {xx -> x, tt -> t};

TAtomPolynomial::usage = "TAtomPolynomial[alpha, x, t] returns the t-deformed Demazure atom obtained by applying TDemazureAtomOperator along the sorting word of alpha to x^sort(alpha); t = 0 gives AtomPolynomial.";
TAtomPolynomial[alpha_?weakCompositionQ, x_, t_] := cached[{TAtomPolynomial, alpha},
	TDemazureAtomOperator[monomial[Sort[alpha, Greater], xx], xx, tt, sortingWord[alpha]]] /. {xx -> x, tt -> t};

permutationQ[w_] := VectorQ[w, IntegerQ] && Sort[w] === Range[Length[w]];

PermutationToCode::usage = "PermutationToCode[w] returns the Lehmer code of the permutation w (one-line notation): entry i counts j > i with w[[j]] < w[[i]].";
PermutationToCode[w_?permutationQ] := Table[Count[w[[i + 1 ;;]], v_ /; v < w[[i]]], {i, Length[w]}];

CodeToPermutation::usage = "CodeToPermutation[c] returns the permutation (one-line notation) with Lehmer code c, in the smallest symmetric group that contains it.";
CodeToPermutation[c_?weakCompositionQ] := Module[{n = Max[Length[c], Max[MapIndexed[#1 + First[#2] &, c], 0]], code, avail, w},
	code = PadRight[c, n]; avail = Range[n];
	w = Table[With[{v = avail[[code[[i]] + 1]]}, avail = DeleteCases[avail, v]; v], {i, n}];
	(* Drop trailing fixed points. *)
	While[Length[w] > 0 && Last[w] == Length[w], w = Most[w]];
	w
];

SchubertPolynomial::usage = "SchubertPolynomial[w, x] returns the Schubert polynomial of the permutation w (one-line notation), computed by divided differences from x[1]^(n-1) x[2]^(n-2) ... x[n-1] for the longest permutation of n letters.";
SchubertPolynomial[w_?permutationQ, x_] := cached[{SchubertPolynomial, w},
	Module[{n = Length[w]},
		(* Bubble-sorting w into decreasing order gives a word with
		   w s_i1 ... s_ik = w0, so S_w = d_i1 ... d_ik S_w0 (d_ik acting first). *)
		DividedDifference[Times @@ Table[xx[i]^(n - i), {i, n}], xx, sortingWord[w]]]] /. xx -> x;


