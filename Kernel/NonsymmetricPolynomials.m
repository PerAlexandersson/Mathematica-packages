(* Nonsymmetric polynomials: divided difference and Demazure operators, and the key,
   atom, t-key, t-atom and Schubert polynomial families generated by them (issue #51).
   Polynomials are expressions in x[1], ..., x[n]; families are also available as basis
   symbols (KeySymbol[alpha, x], ...) with conversions in both directions.
   Conventions (CONVENTIONS.md): keys and atoms are indexed by weak compositions in the
   standard way, kappa_(0,1) = x[1] + x[2], as in the Rust sym-poly library. *)

